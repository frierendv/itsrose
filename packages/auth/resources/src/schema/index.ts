import type { BetterAuthPlugin, BetterAuthPluginDBSchema } from "better-auth";

/**
 * Plugin id used for the schema-only registration in `@itsrose/auth`.
 *
 * The resources package has no transport plugin: the host application composes
 * its own routes and passes the ports they need. Registering the ledger schema
 * through a separate, endpoint-free plugin in the auth composition root keeps
 * the generated SQL the single source of truth for DDL.
 */
export const RESOURCES_SCHEMA_PLUGIN_ID = "resources-schema";

/**
 * Table that records the upstream provider resources a user owns.
 */
export const PROVIDER_RESOURCES_TABLE = "provider_resources";

/**
 * Table that records each studio generation as metadata.
 *
 * Bytes are not stored here. A generated object lives under the ephemeral
 * `t/users/{userId}/generated/` root with a one-day lifecycle, and the row
 * points at it through `result_key`; saving the result to the library is a
 * separate, explicit step that sets `result_asset_id`.
 */
export const GENERATIONS_TABLE = "generations";

/**
 * Better Auth database schema for the resources ledger.
 *
 * It carries two tables. `provider_resources` records the upstream provider
 * objects a user owns: the row — not the upstream id list — is what grants
 * ownership. Every voice an ElevenLabs clone creates lives in one platform
 * account behind one API key, so `GET /v2/voices` cannot say whose clone is
 * whose; holding a `voice_id` is not a capability on our side, because every
 * caller of the shared key already has it. Only a row can be scoped by
 * `user_id`, survive the upstream object it describes, and be the thing
 * account deletion purges.
 *
 * `generations` records what the studio produced and with which inputs. It is
 * a ledger, not a library: the generated bytes stay ephemeral, and
 * `result_asset_id` links a saved result to its durable row.
 *
 * `id` is intentionally absent — Better Auth adds its own primary key to
 * every table and the adapter supplies it on insert — while `resource_id` and
 * `generation_id` are the application identities the dashboard and studio
 * routes address, so each carries its own unique index. The composite unique
 * index on `(provider, provider_resource_id)` is the lookup duplicate
 * ownership and synthesis checks use: an upstream id is unique per provider
 * account, and v1 records voices from one account only.
 */
export const providerResourcesSchema = {
	[PROVIDER_RESOURCES_TABLE]: {
		modelName: PROVIDER_RESOURCES_TABLE,
		fields: {
			/** Application identity of the resource, unique per row. */
			resource_id: { type: "string", required: true },
			/** Upstream provider, `elevenlabs` first. */
			provider: { type: "string", required: true },
			/** The upstream id: `voice_id` for kind `voice`. */
			provider_resource_id: { type: "string", required: true },
			/**
			 * Recorded beside `user_id` for the same reason the asset registry
			 * does it: the object is user-scoped, but caps and analytics are
			 * tenant-wide.
			 */
			tenant_id: { type: "string", required: true },
			/** The owner. The only field enforcement reads. */
			user_id: { type: "string", required: true },
			/**
			 * Closed enum owned by the studio package; `voice` is the first and
			 * only member in v1. A future kind is added here before use.
			 */
			kind: { type: "string", required: true },
			/** The user-chosen display name as given to the provider. */
			name: { type: "string", required: true },
			/**
			 * The durable asset the clone was made from. Nullable in the schema;
			 * the application requires it for `voice`.
			 */
			sample_asset_id: { type: "string", required: false },
			/** `active` while the upstream object exists. */
			status: {
				type: "string",
				required: true,
				defaultValue: "active",
			},
			created_at: { type: "date", required: true },
			/** Soft delete marker; set only after the upstream delete succeeds. */
			deleted_at: { type: "date", required: false },
		},
		indexes: [
			{
				name: "provider_resources_resource_id_uniq",
				fields: ["resource_id"],
				unique: true,
			},
			{
				name: "provider_resources_provider_resource_uniq",
				fields: ["provider", "provider_resource_id"],
				unique: true,
			},
			{ name: "provider_resources_user_id_idx", fields: ["user_id"] },
			{
				name: "provider_resources_tenant_id_idx",
				fields: ["tenant_id"],
			},
			{ name: "provider_resources_kind_idx", fields: ["kind"] },
		],
	},
	[GENERATIONS_TABLE]: {
		modelName: GENERATIONS_TABLE,
		fields: {
			/**
			 * Application identity, chosen by the service before the row is
			 * written. A failed or retried generation keeps one id.
			 */
			generation_id: { type: "string", required: true },
			/**
			 * Recorded beside `user_id` for the same reason every other ledger
			 * does it: the row is user-scoped, but caps and analytics are
			 * tenant-wide.
			 */
			tenant_id: { type: "string", required: true },
			/** The caller. The only ownership field any read checks. */
			user_id: { type: "string", required: true },
			/**
			 * Closed union owned by this package. Adding a feature is a
			 * schema-adjacent change: extend `GENERATION_FEATURES` in
			 * `types.ts` and this comment together, in the same change that
			 * starts writing rows for it, so a read never has to guess what an
			 * unknown string means.
			 */
			feature: { type: "string", required: true },
			/** Upstream provider, `elevenlabs` first. */
			provider: { type: "string", required: true },
			/** Async providers only; the upstream task id, when there is one. */
			provider_task_id: { type: "string", required: false },
			/**
			 * Execution status only: `pending`, `succeeded`, `failed`.
			 *
			 * `expired` is never stored — it is derived from `expires_at` and
			 * a null `result_asset_id` — so no background job has to rewrite a
			 * row.
			 */
			status: {
				type: "string",
				required: true,
				defaultValue: "succeeded",
			},
			/** The prompt/text the user submitted. Never audio bytes. */
			input_text: { type: "string", required: false },
			/**
			 * Sanitised JSON text of the other request parameters.
			 *
			 * Text, not a JSON column: Better Auth supports one (its
			 * `DBFieldType` includes `"json"`, generated as `jsonb` on
			 * Postgres), but the value arrives already serialised and
			 * sanitised as text, the row is display-only, and no query reads
			 * the structure. Keeping it opaque avoids marshalling a
			 * structured value the package would then have to validate on
			 * both the port and the adapter boundary.
			 */
			input_params: { type: "string", required: false },
			/**
			 * Object key under the ephemeral `t/users/{userId}/generated/`
			 * root, set when a result was stored.
			 */
			result_key: { type: "string", required: false },
			result_content_type: { type: "string", required: false },
			/**
			 * Durable `asset_registry.asset_id`, set only when the user saved
			 * the result to the library. Sending a result to the library is a
			 * separate step: the key keeps its one-day life either way.
			 */
			result_asset_id: { type: "string", required: false },
			/**
			 * The generated object's lifecycle deadline, created plus one day;
			 * null when no result was stored. Advisory — the bucket rule
			 * enforces it — so a live row can carry a past deadline without
			 * being rewritten.
			 */
			expires_at: { type: "date", required: false },
			created_at: { type: "date", required: true },
			/** Soft delete marker when the owner clears a history row. */
			deleted_at: { type: "date", required: false },
		},
		indexes: [
			{
				name: "generations_generation_id_uniq",
				fields: ["generation_id"],
				unique: true,
			},
			{
				name: "generations_user_id_created_at_idx",
				fields: ["user_id", "created_at"],
			},
			{
				name: "generations_tenant_id_created_at_idx",
				fields: ["tenant_id", "created_at"],
			},
		],
	},
} satisfies BetterAuthPluginDBSchema;

/**
 * Schema-only Better Auth plugin, registered by `@itsrose/auth`.
 *
 * The studio routes are composed by the host application, so `db:generate`
 * (driven by the auth composition root) would never see the ledger tables.
 * This plugin carries the schema alone, and declaring it only once avoids
 * merging the same table definitions twice.
 */
export const providerResourcesSchemaPlugin = {
	id: RESOURCES_SCHEMA_PLUGIN_ID,
	schema: providerResourcesSchema,
	endpoints: {},
} satisfies BetterAuthPlugin;
