import { z } from "zod/v4";
import {
	BaseTransactionResultSchema,
	CustomFieldsSchema,
	PaymentAmountSchema,
} from "../primitives";

/**
 * Midtrans HTTP POST Notification (Webhook) payload.
 *
 * Sent by Midtrans to the merchant configured Payment Notification URL.
 *
 * `gross_amount` is inherited from {@link BaseTransactionResultSchema} and is
 * therefore the raw 2-decimal string Midtrans signed (`"15000.00"`), exactly
 * like {@link InvoiceWebhookSchema} exposes it. The two webhook schemas can no
 * longer disagree about the signed field.
 */
export const WebhookPayloadSchema = BaseTransactionResultSchema.extend(
	CustomFieldsSchema.shape
)
	.extend({
		signature_key: z
			.string()
			.describe("SHA-512 hex signature generated by Midtrans"),
		settlement_time: z.string().optional(),
		expiry_time: z.string().optional(),
		payment_amounts: z.array(PaymentAmountSchema).optional(),
		metadata: z.record(z.string(), z.unknown()).optional(),
		/**
		 * Customer details attached to the transaction.
		 *
		 * Midtrans always sends the key; it is an empty object when the
		 * transaction carries no customer data.
		 */
		customer_details: z.record(z.string(), z.unknown()).optional(),
	})
	.meta({
		id: "MidtransWebhookNotification",
	});

export type WebhookPayload = z.infer<typeof WebhookPayloadSchema>;

/** @deprecated Use {@link WebhookPayloadSchema}. */
export const WebhookPayload = WebhookPayloadSchema;
