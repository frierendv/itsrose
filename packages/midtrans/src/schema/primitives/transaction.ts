import { z } from "zod/v4";

/* -------------------------------- Status --------------------------------- */

/**
 * The `transaction_status` used by Midtrans API.
 */
export const TransactionStatusSchema = z
	.enum([
		"authorize",
		"capture",
		"settlement",
		"deny",
		"pending",
		"cancel",
		"refund",
		"partial_refund",
		"chargeback",
		"partial_chargeback",
		"expire",
		"failure",
	])
	.meta({
		id: "MidtransTransactionStatus",
	});
export type TransactionStatus = z.infer<typeof TransactionStatusSchema>;

/**
 * Fraud status used by Midtrans API.
 */
export const TransactionFraudStatusSchema = z.enum([
	"accept",
	"challenge",
	"deny",
]);
export type TransactionFraudStatus = z.infer<
	typeof TransactionFraudStatusSchema
>;

/**
 * Alias kept for callers that import the fraud status schema by its historical name.
 */
export const FraudStatusSchema = TransactionFraudStatusSchema;
export type FraudStatus = TransactionFraudStatus;

/* -------------------------- Transaction Details -------------------------- */

/**
 * Midtrans transaction details object.
 */
export const TransactionDetailsSchema = z
	.object({
		/** Unique order identifier generated by merchant. */
		order_id: z
			.string()
			.min(1)
			.max(50)
			.regex(/^[a-zA-Z0-9._~-]+$/, {
				message:
					"Only alphanumeric characters and the symbols -, _, ~, and . are allowed.",
			}),
		/** Total payment amount Customer expected to pay. */
		gross_amount: z.number().int().positive(),
	})
	.meta({
		id: "MidtransTransactionDetails",
	});
export type TransactionDetails = z.infer<typeof TransactionDetailsSchema>;

/* ----------------------------- Actions & VAs ----------------------------- */

/**
 * Virtual account number entry returned by bank transfer payment methods.
 */
export const VaNumberSchema = z
	.object({
		bank: z
			.string()
			.describe("Target bank (e.g. bca, bni, bri, permata, cimb)"),
		va_number: z.string().describe("Virtual account number to pay to"),
	})
	.meta({
		id: "MidtransVaNumber",
	});
export type VaNumber = z.infer<typeof VaNumberSchema>;

/**
 * Deep-link, QR code, or action redirect returned by e-wallets or QRIS.
 */
export const PaymentActionSchema = z
	.object({
		name: z
			.string()
			.describe(
				"Action identifier (e.g. 'generate-qr-code', 'deeplink-redirect')"
			),
		method: z.string().describe("HTTP method (e.g. 'GET')"),
		url: z
			.string()
			.url()
			.describe("Target URL to execute action or redirect"),
	})
	.meta({
		id: "MidtransPaymentAction",
	});
export type PaymentAction = z.infer<typeof PaymentActionSchema>;

/**
 * Partial payment amount entry if transaction was split or paid incrementally.
 */
export const PaymentAmountSchema = z
	.object({
		paid_at: z.string().describe("Timestamp of the partial payment"),
		amount: z.string().describe("Amount paid in this chunk"),
	})
	.meta({
		id: "MidtransPaymentAmount",
	});
export type PaymentAmount = z.infer<typeof PaymentAmountSchema>;

/* ----------------------- Base Transaction Result ------------------------- */

/**
 * Canonical transaction result schema representing payment status across Core API, Snap, and Webhooks.
 */
export const BaseTransactionResultSchema = z
	.object({
		status_code: z
			.string()
			.describe("Payment transaction status code (e.g. '200', '201')"),
		status_message: z
			.string()
			.describe("Human readable status description"),
		transaction_id: z
			.string()
			.describe("Midtrans unique transaction identifier (UUID)"),
		order_id: z.string().describe("Merchant unique order identifier"),
		merchant_id: z.string().optional().describe("Midtrans merchant ID"),
		gross_amount: z
			.string()
			.describe(
				"Transaction gross amount formatted as string (e.g. '10000.00')"
			),
		currency: z
			.string()
			.default("IDR")
			.describe("Transaction currency code"),
		payment_type: z
			.string()
			.describe(
				"Payment channel used (e.g. 'bank_transfer', 'qris', 'gopay')"
			),
		transaction_time: z
			.string()
			.describe("Timestamp when transaction was created"),
		transaction_status: z
			.string()
			.describe(
				"Transaction lifecycle status (e.g. 'settlement', 'pending')"
			),
		fraud_status: z
			.string()
			.optional()
			.describe("Fraud detection status ('accept', 'challenge', 'deny')"),

		// Bank transfer specific fields
		va_numbers: z.array(VaNumberSchema).optional(),
		permata_va_number: z.string().optional(),

		// Mandiri Bill (echannel)
		bill_key: z.string().optional(),
		biller_code: z.string().optional(),

		// QRIS & E-Wallets
		actions: z.array(PaymentActionSchema).optional(),
		qr_string: z.string().optional(),
		acquirer: z.string().optional(),

		// Over the counter (cstorage: Indomaret / Alfamart)
		payment_code: z.string().optional(),
		store: z.string().optional(),

		// Credit card
		masked_card: z.string().optional(),
		card_type: z.string().optional(),
		bank: z.string().optional(),
		approval_code: z.string().optional(),
		eci: z.string().optional(),
		three_ds_version: z.string().optional(),
		on_us: z.boolean().optional(),
		channel_response_code: z.string().optional(),
		channel_response_message: z.string().optional(),
		saved_token_id: z.string().optional(),

		// Shared lifecycle metadata
		expiry_time: z.string().optional(),
		settlement_time: z.string().optional(),
	})
	.meta({
		id: "MidtransBaseTransactionResult",
	});
export type BaseTransactionResult = z.infer<typeof BaseTransactionResultSchema>;
