import { requestPixverse } from "../client/send";
import type { PixverseTaskResult } from "../zod-schema";
import { PixverseTaskResultSchema } from "../zod-schema";

/**
 * Queries the result of a video generation task.
 *
 * The call is a plain GET on the task, so it is safe to repeat and it
 * inherits the shared retry contract. It answers the task whatever its
 * state is: the caller decides what a `status` of `5` means, and should
 * keep polling every 3-5 seconds until the task is terminal.
 *
 * @param video_id The identifier a creation endpoint returned.
 * @returns The current state of the task.
 * @throws {UpstreamApiError} When PixVerse refused the query - for example
 * with `500008` (not found) or `500085` (generated by another account).
 */
export async function getTask(
	video_id: number | string
): Promise<PixverseTaskResult> {
	return requestPixverse({
		url: `/openapi/v2/video/result/${encodeURIComponent(String(video_id))}`,
		method: "GET",
		schema: PixverseTaskResultSchema,
		label: "task result",
	});
}
