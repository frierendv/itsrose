import { z } from "zod/v4";
import { requestPixverse } from "../client/send";
import { toTaskResponse } from "../utils/translate-task";
import type { PixverseTaskResponse, PixverseTaskResult } from "../zod-schema";
import {
	PixverseTaskResponseSchema,
	PixverseTaskResultSchema,
} from "../zod-schema";

/**
 * The query of {@linkcode getTask}.
 */
export const GetTaskSchema = z
	.object({
		task_id: z
			.string()
			.min(1)
			.describe("Task id, as returned by a creation endpoint."),
	})
	.meta({ id: "PixverseGetTaskQuery" });

export type GetTask = z.infer<typeof GetTaskSchema>;

/**
 * Queries the result of a video generation task.
 *
 * The call is a plain GET on the task, so it is safe to repeat and it
 * inherits the shared retry contract. It answers the task whatever its
 * state is; the caller decides what to do with `in_progress`, and
 * {@linkcode waitForTask} is the helper that polls to a terminal state.
 *
 * @param query The task to query.
 * @returns The task, in the status vocabulary this package publishes.
 * @throws {UpstreamApiError} When PixVerse refused the query - for example
 * with `500008` (not found) or `500085` (generated by another account).
 */
export async function getTask(
	query: GetTask | string | number
): Promise<PixverseTaskResponse> {
	const { task_id } =
		typeof query === "object"
			? GetTaskSchema.parse(query)
			: { task_id: String(query) };

	const result = await requestPixverse<PixverseTaskResult>({
		url: `/openapi/v2/video/result/${encodeURIComponent(task_id)}`,
		method: "GET",
		schema: PixverseTaskResultSchema,
		label: "task result",
	});

	return toTaskResponse(result);
}

/**
 * The request and response schemas of {@linkcode getTask}.
 */
export const getTaskSchema = {
	request: GetTaskSchema,
	response: PixverseTaskResponseSchema,
} as const;
