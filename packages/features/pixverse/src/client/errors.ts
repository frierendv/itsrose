/**
 * Reads the `ErrCode` out of an untrusted error body.
 *
 * @param payload The raw payload the upstream answered with.
 * @returns The business code, when the payload carries one.
 */
export function readErrorCode(payload: unknown): number | undefined {
	if (!payload || typeof payload !== "object") {
		return undefined;
	}

	const code = (payload as { ErrCode?: unknown }).ErrCode;

	return typeof code === "number" && Number.isInteger(code)
		? code
		: undefined;
}

/**
 * Reads the most specific message an error body carries.
 *
 * `Error.Message` describes the cause and the suggested change, `ErrMsg` is
 * only a short summary - so the detail wins when PixVerse sent one.
 *
 * @param payload The raw payload the upstream answered with.
 * @returns The message, when the payload carries one.
 */
export function readErrorMessage(payload: unknown): string | undefined {
	if (!payload || typeof payload !== "object") {
		return undefined;
	}

	const detail = PixverseErrorDetailSchema.safeParse(
		(payload as { Error?: unknown }).Error
	);

	if (detail.success && detail.data.Message) {
		return detail.data.Message;
	}

	const message = (payload as { ErrMsg?: unknown }).ErrMsg;

	return typeof message === "string" && message ? message : undefined;
}

/**
 * Maps a PixVerse failure onto the message and status a caller sees.
 *
 * PixVerse answers `HTTP 200` for a failed operation, so the envelope's
 * `ErrCode` is read from the body rather than from the status.
 *
 * @param payload The raw, untrusted error body.
 * @param context The upstream the call was made against.
 * @returns The message and status to report, or `undefined` to let the
 * client decide.
 */
export const mapPixverseError: UpstreamErrorMapper = (payload, context) => {
	const code = readErrorCode(payload);

	if (code === undefined || code === 0) {
		return undefined;
	}

	const known = PIXVERSE_ERROR_MAP[code];
	const detail = readErrorMessage(payload);

	if (known) {
		return {
			message: detail ?? known.message,
			statusCode: known.statusCode,
		};
	}

	return {
		message: detail ?? `PixVerse answered with error code ${code}.`,
		statusCode:
			context.status && context.status >= 400 ? context.status : 500,
	};
};
