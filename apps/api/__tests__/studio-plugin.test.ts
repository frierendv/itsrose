import { createHash } from "node:crypto";
import type { AuthServer } from "@itsrose/auth/server";
import type {
	IElevenLabsSharedResponse,
	IElevenLabsTextToSpeechConvert,
} from "@itsrose/elevenlabs";
import {
	contentTypeFor,
	createStudioSpeech,
	createStudioStore,
	type StudioObjects,
	type StudioSynthesizer,
} from "../src/plugins/app/07-studio";

const USER_ID = "user-1";
const AUDIO = Buffer.from([0xff, 0xfb, 0x90, 0x00, 0x2a]);

/** The filename the store must derive from the bytes. */
const EXPECTED_FILENAME = createHash("sha256")
	.update(AUDIO)
	.digest("hex")
	.slice(0, 16);

type UploadCall = {
	userId: string;
	category: string;
	filename: string;
	data: Buffer | string;
	contentType: string | undefined;
};

/**
 * Builds an auth server whose storage plugin records its uploads.
 */
function createAuth(calls: UploadCall[]): AuthServer {
	return {
		$context: Promise.resolve({
			storage: {
				async uploadUserFile(
					userId: string,
					category: string,
					filename: string,
					data: Buffer | string,
					options?: { contentType?: string }
				) {
					calls.push({
						userId,
						category,
						filename,
						data,
						contentType: options?.contentType,
					});
					return {
						key: `t/users/${userId}/${category}/${filename}`,
						publicUrl: `https://cdn.test/${filename}`,
					};
				},
			},
		}),
	} as unknown as AuthServer;
}

/**
 * Builds the object-storage surface the store falls back to.
 */
function createObjects(overrides: Partial<StudioObjects> = {}): {
	objects: StudioObjects;
	deleted: string[];
} {
	const deleted: string[] = [];

	const objects: StudioObjects = {
		getPublicUrl: () => "https://cdn.test/generated.mp3",
		async delete(key) {
			deleted.push(key);
		},
		...overrides,
	};

	return { objects, deleted };
}

describe("contentTypeFor", () => {
	it.each([
		["mp3_44100_128", "audio/mpeg"],
		["wav_16000", "audio/wav"],
		["opus_48000_64", "audio/ogg"],
		// The provider's default is MP3, and any other container is treated
		// as MP3 rather than guessed.
		[undefined, "audio/mpeg"],
		["pcm_16000", "audio/mpeg"],
	] as const)("maps %s to %s", (format, expected) => {
		expect(contentTypeFor(format)).toBe(expected);
	});
});

describe("createStudioSpeech", () => {
	it("decodes the base64 audio and reports the content type", async () => {
		const requests: IElevenLabsTextToSpeechConvert[] = [];
		const synthesize: StudioSynthesizer = async (input) => {
			requests.push(input);
			return { audio: AUDIO.toString("base64") };
		};
		const speech = createStudioSpeech(synthesize);

		const generated = await speech.generate({
			text: "Hello.",
			voice_id: "voice-1",
			model_id: "eleven_multilingual_v2",
			output_format: "wav_16000",
		});

		expect(generated.data).toEqual(AUDIO);
		expect(generated.contentType).toBe("audio/wav");
		expect(requests).toEqual([
			{
				text: "Hello.",
				voice_id: "voice-1",
				model_id: "eleven_multilingual_v2",
				output_format: "wav_16000",
			},
		]);
	});

	it("drops a format the client does not know, so the provider defaults", async () => {
		const requests: IElevenLabsTextToSpeechConvert[] = [];
		const synthesize: StudioSynthesizer = async (input) => {
			requests.push(input);
			return {
				audio: AUDIO.toString("base64"),
			} satisfies IElevenLabsSharedResponse;
		};
		const speech = createStudioSpeech(synthesize);

		const generated = await speech.generate({
			text: "Hello.",
			voice_id: "voice-1",
			output_format: "flac_16000",
		});

		expect(generated.contentType).toBe("audio/mpeg");
		expect(requests).toEqual([{ text: "Hello.", voice_id: "voice-1" }]);
	});

	it("omits the optional parameters when the caller did not send them", async () => {
		const requests: IElevenLabsTextToSpeechConvert[] = [];
		const speech = createStudioSpeech(async (input) => {
			requests.push(input);
			return { audio: AUDIO.toString("base64") };
		});

		await speech.generate({ text: "Hello.", voice_id: "voice-1" });

		expect(requests).toEqual([{ text: "Hello.", voice_id: "voice-1" }]);
	});
});

describe("createStudioStore", () => {
	it("stores generated bytes under the generated class", async () => {
		const uploads: UploadCall[] = [];
		const { objects } = createObjects();
		const store = createStudioStore({
			auth: createAuth(uploads),
			objects,
		});

		const stored = await store.putGenerated({
			userId: USER_ID,
			data: AUDIO,
			contentType: "audio/mpeg",
		});

		expect(uploads).toEqual([
			{
				userId: USER_ID,
				category: "generated",
				filename: EXPECTED_FILENAME,
				data: AUDIO,
				contentType: "audio/mpeg",
			},
		]);
		expect(stored).toEqual({
			key: `t/users/${USER_ID}/generated/${EXPECTED_FILENAME}`,
			url: `https://cdn.test/${EXPECTED_FILENAME}`,
		});
	});

	it("resolves a generated public URL, and fails when none is configured", () => {
		const { objects } = createObjects();
		const store = createStudioStore({
			auth: createAuth([]),
			objects,
		});

		expect(store.publicUrl("t/users/user-1/generated/abc")).toBe(
			"https://cdn.test/generated.mp3"
		);

		const { objects: unroutable } = createObjects({
			getPublicUrl: () => null,
		});
		const withoutDomain = createStudioStore({
			auth: createAuth([]),
			objects: unroutable,
		});

		expect(() =>
			withoutDomain.publicUrl("t/users/user-1/generated/abc")
		).toThrow(/no public URL/i);
	});

	it("removes the object through the bucket client", async () => {
		const { objects, deleted } = createObjects();
		const store = createStudioStore({
			auth: createAuth([]),
			objects,
		});

		await store.remove("t/users/user-1/generated/abc");

		expect(deleted).toEqual(["t/users/user-1/generated/abc"]);
	});
});
