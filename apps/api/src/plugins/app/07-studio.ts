import {
	createGenerationService,
	type GenerationService,
} from "@itsrose/auth-resources/generations";
import { createPostgresGenerationRegistry } from "@itsrose/auth-resources/registry";
import { getStorageClient } from "@itsrose/auth-storage";
import type { AuthServer } from "@itsrose/auth/server";
import {
	ElevenLabsOutputFormatSchema,
	textToSpeech,
	type IElevenLabsSharedResponse,
	type IElevenLabsTextToSpeechConvert,
} from "@itsrose/elevenlabs";
import { SystemError } from "@itsrose/system";
import fp from "fastify-plugin";

/* -------------------------------------------------------------------------- */
/*                                   Ports                                    */
/* -------------------------------------------------------------------------- */

/** One synthesis request from a studio route. */
export type StudioSpeechInput = {
	/** The text to speak; the route caps it before it reaches the port. */
	text: string;
	/** The voice to speak with; the route authenticated it first. */
	voice_id: string;
	/** The upstream model to use; the provider's default when omitted. */
	model_id?: string;
	/** The audio format to return; the provider's default when omitted. */
	output_format?: string;
};

/** The audio one synthesis produced. */
export type StudioGeneratedAudio = {
	/** The decoded audio bytes. */
	data: Buffer;
	/** The content type of those bytes. */
	contentType: string;
};

/**
 * The synthesis port the speech route calls.
 *
 * Declared here so the route never imports the ElevenLabs client and a test
 * can answer with canned audio.
 */
export interface StudioSpeechPort {
	/** Synthesises speech from text and returns its bytes. */
	generate(input: StudioSpeechInput): Promise<StudioGeneratedAudio>;
}

/** One generated object to store under the generated class. */
export type StudioPutGeneratedInput = {
	/** The owner; the key is user-scoped. */
	userId: string;
	/** The audio bytes. */
	data: Buffer;
	/** The content type stored beside the bytes. */
	contentType: string;
};

/** One stored generated object. */
export type StudioStoredObject = {
	/** Ephemeral key under `t/users/{userId}/generated/`. */
	key: string;
	/** Public URL the object is readable through while it lives. */
	url: string;
};

/**
 * The ephemeral object port the studio routes call.
 *
 * The store only knows the generated class: its objects are public, expire
 * under the one-day lifecycle rule and are never counted against the storage
 * entitlement. Durability is the asset service's job, on promotion.
 */
export interface StudioStorePort {
	/** Stores generated bytes and returns their key and public URL. */
	putGenerated(input: StudioPutGeneratedInput): Promise<StudioStoredObject>;
	/** Resolves the public URL of an existing generated object. */
	publicUrl(key: string): string;
	/** Removes one generated object. */
	remove(key: string): Promise<void>;
}

/* -------------------------------------------------------------------------- */
/*                                   Store                                    */
/* -------------------------------------------------------------------------- */

/**
 * The category API-generated output is stored under.
 *
 * It selects the generated storage class: rooted at `t/`, readable through a
 * public URL, expired after one day and uncounted until promoted.
 */
const GENERATED_CATEGORY = "generated";

/**
 * Derives the object filename from the bytes.
 *
 * The caller never names the object: the name is a truncated hash of the
 * bytes, so a studio route cannot overwrite or enumerate another key.
 */
function generatedFilename(data: Buffer): string {
	return createHash("sha256").update(data).digest("hex").slice(0, 16);
}

/**
 * The object-storage surface the store needs.
 *
 * Declared structurally so this plugin never imports `@itsrose/s3`; the
 * storage package's singleton client satisfies it.
 */
export type StudioObjects = {
	getPublicUrl(key: string): string | null;
	delete(key: string): Promise<void>;
};

/** Options of {@linkcode createStudioStore}. */
export interface CreateStudioStoreOptions {
	/** The Better Auth server whose storage plugin holds the bucket client. */
	auth: AuthServer;
	/** Omitted, the storage package's singleton client is used. */
	objects?: StudioObjects;
}

/**
 * Builds the generated-object store.
 *
 * Writes go through `auth.$context.storage.uploadUserFile` so the key shape and
 * the public-URL resolution stay the storage package's contract; reads and
 * deletes use the same singleton bucket client the asset plugin uses.
 *
 * @param options - The auth server and the optional objects override.
 * @returns The store the studio routes call.
 */
export function createStudioStore({
	auth,
	objects,
}: CreateStudioStoreOptions): StudioStorePort {
	const resolveObjects = (): StudioObjects => objects ?? getStorageClient();

	return {
		async putGenerated({ userId, data, contentType }) {
			const { storage } = await auth.$context;
			const stored = await storage.uploadUserFile(
				userId,
				GENERATED_CATEGORY,
				generatedFilename(data),
				data,
				{ contentType }
			);

			return { key: stored.key, url: stored.publicUrl };
		},

		publicUrl(key) {
			const url = resolveObjects().getPublicUrl(key);
			if (!url) {
				throw new SystemError(
					`No public URL is configured for the generated object "${key}".`
				);
			}
			return url;
		},

		remove(key) {
			return resolveObjects().delete(key);
		},
	};
}

