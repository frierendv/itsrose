/*                                  Plugin                                    */
/* -------------------------------------------------------------------------- */

/**
 * The studio's three ports: the generation ledger, the generated-object store
 * and the speech client.
 *
 * Decorating them here keeps the route handlers to mapping and calls: they
 * never touch the database, the bucket or the ElevenLabs SDK. The ledger is
 * the same application service the account-deletion purge composes, so the
 * record/list/save/clear rules live in `@itsrose/auth-resources`.
 */
export default fp(
	async (fastify) => {
		const generationService = createGenerationService({
			registry: createPostgresGenerationRegistry(fastify.database),
			clock: () => new Date(),
			newId: () => randomUUID(),
		});

		void fastify.decorate("generationService", generationService);
		void fastify.decorate(
			"studioStore",
			createStudioStore({ auth: fastify.auth })
		);
		void fastify.decorate("studioSpeech", createStudioSpeech());
	},
	{
		name: "studio",
		dependencies: ["auth", "database"],
	}
);

declare module "fastify" {
	interface FastifyInstance {
		/** The generation ledger: record, list, find, save and clear. */
		generationService: GenerationService;
		/** The ephemeral store for generated output. */
		studioStore: StudioStorePort;
		/** The text-to-speech port. */
		studioSpeech: StudioSpeechPort;
	}
}
