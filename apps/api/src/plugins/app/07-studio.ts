/*                                  Speech                                    */
/* -------------------------------------------------------------------------- */

/**
 * The synthesis call the speech port is built over.
 *
 * Injected so a test can answer with canned audio; the plugin composes it with
 * the real ElevenLabs client.
 */
export type StudioSynthesizer = (
	input: IElevenLabsTextToSpeechConvert
) => Promise<IElevenLabsSharedResponse>;

/**
 * Resolves the content type a requested output format produces.
 *
 * The format names carry their container as a prefix (`mp3_44100_128`,
 * `wav_44100`, `opus_48000_64`); anything else — including the provider's
 * default — is MP3.
 *
 * @param outputFormat - The format the caller asked for, when it asked.
 * @returns The audio content type.
 */
export function contentTypeFor(outputFormat: string | undefined): string {
	if (outputFormat?.startsWith("mp3")) {
		return "audio/mpeg";
	}
	if (outputFormat?.startsWith("wav")) {
		return "audio/wav";
	}
	if (outputFormat?.startsWith("opus")) {
		return "audio/ogg";
	}
	return "audio/mpeg";
}

/**
 * Narrows a caller-supplied format to the client's closed union.
 *
 * The route accepts a free string, but the client would send whatever it was
 * given upstream; an unrecognised format is dropped so the provider answers
 * with its default instead of rejecting the whole synthesis.
 *
 * @param value - The requested format, when one was requested.
 * @returns The format the client accepts, or `undefined`.
 */
function parseOutputFormat(
	value: string | undefined
): IElevenLabsTextToSpeechConvert["output_format"] {
	if (value === undefined) {
		return undefined;
	}

	const parsed = ElevenLabsOutputFormatSchema.safeParse(value);
	return parsed.success ? parsed.data : undefined;
}

/**
 * Builds the speech port the studio route calls.
 *
 * The client answers with base64 audio; the port decodes it and reports the
 * content type that matches the format actually requested.
 *
 * @param synthesize - The upstream call; the real client by default.
 * @returns The speech port.
 */
export function createStudioSpeech(
	synthesize: StudioSynthesizer = textToSpeech
): StudioSpeechPort {
	return {
		async generate({ text, voice_id, model_id, output_format }) {
			const format = parseOutputFormat(output_format);
			const request: IElevenLabsTextToSpeechConvert = { text, voice_id };
			if (model_id !== undefined) {
				request.model_id = model_id;
			}
			if (format !== undefined) {
				request.output_format = format;
			}

			const { audio } = await synthesize(request);

			return {
				data: Buffer.from(audio, "base64"),
				contentType: contentTypeFor(format),
			};
		},
	};
}

